import React from 'react'
import { HugeiconsIcon } from '@hugeicons/react'
import * as H from '@hugeicons/core-free-icons'

/**
 * The app's icons, from Hugeicons. Each icon is exported under the name the app already uses for
 * it, so a screen imports { Folder, Search, X } from '@/components/icons' and uses it like before
 * (size, className and strokeWidth work the same). To swap one icon for another, change the
 * Hugeicons name on its line below; nothing else needs to change.
 * `npm run check:icons` lists any name below that the installed Hugeicons package does not have.
 */
type IconData = React.ComponentProps<typeof HugeiconsIcon>['icon']
export type IconProps = Omit<React.ComponentProps<typeof HugeiconsIcon>, 'icon'>
export type IconComponent = (props: IconProps) => React.JSX.Element

// Shown (and logged once) if a name below is wrong, so one bad name never breaks a screen.
const FALLBACK: IconData = H.AlertCircleIcon

function make(icon: IconData | undefined): IconComponent {
  if (!icon) console.warn('An icon name in components/icons.tsx is not in the Hugeicons package')
  const data = icon ?? FALLBACK
  const Icon: IconComponent = (props) => <HugeiconsIcon icon={data} size={24} {...props} />
  return Icon
}

