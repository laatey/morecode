#!/usr/bin/env node
/**
 * Builds src/renderer/src/theme/vscode-themes-generated.ts from VS Code's own built-in theme files.
 *
 *   git clone --depth 1 --filter=blob:none --sparse https://github.com/microsoft/vscode.git
 *   (cd vscode && git sparse-checkout set --no-cone '/extensions/theme-*')
 *   npm run themes:generate -- ./vscode
 *
 * It mirrors how VS Code loads a theme: `include` is resolved first (the parent's colours, then the child's
 * on top; token rules concatenated parent-first), JSONC comments and trailing commas are accepted, and only
 * the colour keys MoreCode reads are kept. The output is committed, so building the app never needs VS Code.
 */
import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { UI_KEYS } from '../src/renderer/src/theme/vscode-keys.ts'

const root = resolve(process.argv[2] ?? process.env.VSCODE_DIR ?? '../vscode')
const extensions = join(root, 'extensions')
if (!existsSync(extensions)) {
  console.error(`No VS Code checkout at ${root}. See the header of this script.`)
  process.exit(1)
}

/** JSONC → value. Walks the text so comment markers inside strings (https://…) survive. */
function parseJsonc(text) {
  let out = ''
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (c === '"') {
      let j = i + 1
      while (j < text.length && text[j] !== '"') j += text[j] === '\\' ? 2 : 1
      out += text.slice(i, j + 1)
      i = j
    } else if (c === '/' && text[i + 1] === '/') {
      while (i < text.length && text[i] !== '\n') i++
      out += '\n'
    } else if (c === '/' && text[i + 1] === '*') {
      i = text.indexOf('*/', i + 2) + 1
      if (i === 0) throw new Error('unterminated block comment')
    } else out += c
  }
  return JSON.parse(out.replace(/,(\s*[}\]])/g, '$1'))
}

/** Load a theme file with its `include` chain applied. */
function loadTheme(file) {
  const theme = parseJsonc(readFileSync(file, 'utf8'))
  let colors = {}
  let tokenColors = []
  if (theme.include) {
    const parent = loadTheme(resolve(dirname(file), theme.include))
    colors = parent.colors
    tokenColors = parent.tokenColors
  }
  if (typeof theme.tokenColors === 'string') throw new Error(`${file}: external .tmTheme token files are not supported`)
  return {
    colors: { ...colors, ...(theme.colors ?? {}) },
    tokenColors: [...tokenColors, ...(theme.tokenColors ?? [])]
  }
}

const TYPES = { vs: 'light', 'vs-dark': 'dark', 'hc-black': 'hcDark', 'hc-light': 'hcLight' }
const keep = new Set(UI_KEYS)
const themes = []

for (const dir of readdirSync(extensions).filter((d) => d.startsWith('theme-')).sort()) {
  const pkgFile = join(extensions, dir, 'package.json')
  if (!existsSync(pkgFile)) continue
  const pkg = JSON.parse(readFileSync(pkgFile, 'utf8'))
  const nlsFile = join(extensions, dir, 'package.nls.json')
  const nls = existsSync(nlsFile) ? JSON.parse(readFileSync(nlsFile, 'utf8')) : {}
  for (const t of pkg.contributes?.themes ?? []) {
    const raw = t.label.startsWith('%') ? nls[t.label.slice(1, -1)] : t.label
    const label = typeof raw === 'string' ? raw : raw.message
    const { colors, tokenColors } = loadTheme(resolve(extensions, dir, t.path))
    const ui = {}
    for (const k of Object.keys(colors).sort()) if (keep.has(k)) ui[k] = String(colors[k]).toLowerCase()
    // Syntax: rules that set a foreground. Scopes may be an array or a comma-separated string.
    const tokens = []
    for (const rule of tokenColors) {
      const fg = rule.settings?.foreground
      if (!fg || !rule.scope) continue
      const scopes = (Array.isArray(rule.scope) ? rule.scope : String(rule.scope).split(',')).map((s) => s.trim()).filter(Boolean)
      if (scopes.length) tokens.push({ scope: scopes, color: String(fg).toLowerCase() })
    }
    themes.push({ id: t.id, label, type: TYPES[t.uiTheme], colors: ui, tokens })
  }
}

let sha = 'unknown'
try {
  sha = execFileSync('git', ['-C', root, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim()
} catch {
  // not a git checkout: leave the revision unknown
}

const body = JSON.stringify(themes, null, 1)
const out = `/* eslint-disable */
// GENERATED by scripts/generate-vscode-themes.mjs from microsoft/vscode@${sha}. Do not edit by hand.
import type { VSCodeThemeData } from './types'

export const VSCODE_REVISION = '${sha}'

export const VSCODE_THEMES: VSCodeThemeData[] = ${body}
`
const target = resolve(dirname(fileURLToPath(import.meta.url)), '../src/renderer/src/theme/vscode-themes-generated.ts')
writeFileSync(target, out)
console.log(`${themes.length} themes → ${target} (${(out.length / 1024).toFixed(0)} KB)`)
for (const t of themes) console.log(`  ${t.type.padEnd(7)} ${t.label.padEnd(24)} ${Object.keys(t.colors).length} colours, ${t.tokens.length} syntax rules`)
